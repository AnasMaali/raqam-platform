#!/usr/bin/env bash
# Prints docs/qa/database-coverage.md: every CHECK, domain CHECK, EXCLUDE and trigger function of the schema with the
# tests that broke it, from a real run of the SQL suite (the same files run_tests.sh runs, in a fresh database).
#
#   PGHOST=127.0.0.1 PGUSER=raqam database/tests/coverage-table.sh > docs/qa/database-coverage.md
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
DB="${RAQAM_TEST_DB:-raqam_test}_coverage"
dropdb --if-exists "$DB" 2>/dev/null; createdb "$DB"
trap 'dropdb --if-exists "$DB" 2>/dev/null || true' EXIT
psql -X -q -v ON_ERROR_STOP=1 -d "$DB" -f "$HERE/../raqam_schema.sql"

shopt -s nullglob
FILES=("$HERE/schema_tests.sql" "$HERE"/rules/*.sql "$HERE/coverage.sql")

cat <<'MD'
# Database rules and the tests that break them

Generated by `database/tests/coverage-table.sh` from a run of the SQL suite; `database/tests/coverage.sql` fails the
suite when a rule has no test. A test counts for a rule only when that rule is the one that refused its statement
(and each test names it: refused by another rule, it fails). Background and method: [database.md](database.md).

| Kind | Rule | Table or domain | Broken by |
|---|---|---|---|
MD
{ cat "${FILES[@]}"; cat <<'SQL'
\o
\pset format unaligned
\pset tuples_only on
\pset fieldsep '|'
SELECT '| ' || i.kind || ' | `' || i.name || '` | ' || replace(i.owner, ', ', ' ') || ' | '
       || coalesce((SELECT string_agg(replace(r.label, '|', '/'), '; ' ORDER BY r.n) FROM test_results r WHERE r.ok AND r.broke = i.name),
                   (SELECT 'through `' || x.stand_in || '`: ' || x.reason FROM rule_stand_ins x WHERE x.name = i.name), '**none**')
       || ' |'
FROM rule_items i ORDER BY i.kind, i.owner, i.name;
SQL
} | psql -X -v ON_ERROR_STOP=1 -d "$DB" 2>/dev/null | grep '^| '
