-- ISO 4217. Every money column in the schema references this table.
CREATE TABLE currencies (
  code         char(3)     PRIMARY KEY CHECK (code ~ '^[A-Z]{3}$'),
  name_ar      varchar(60) NOT NULL UNIQUE,
  symbol       varchar(8)  NOT NULL,
  minor_units  smallint    NOT NULL DEFAULT 2 CHECK (minor_units BETWEEN 0 AND 4)
);

CREATE TABLE cities (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_ar    varchar(80)  NOT NULL UNIQUE,
  slug       slug_text    NOT NULL UNIQUE,
  latitude   numeric(9,6) NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
  longitude  numeric(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE sectors (
  id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_ar     varchar(80) NOT NULL UNIQUE,
  slug        slug_text   NOT NULL UNIQUE,
  sort_order  integer     NOT NULL DEFAULT 0
);

-- Companies, factories, NGOs, advertisers, sponsors, initiative organisers.
-- Extracted so a company name/sector/city is stored once (3NF).
CREATE TABLE organizations (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           varchar(160) NOT NULL,
  slug           slug_text    NOT NULL UNIQUE,
  sector_id      smallint REFERENCES sectors (id) ON DELETE SET NULL,
  city_id        integer  REFERENCES cities (id)  ON DELETE SET NULL,
  founded_year   smallint CHECK (founded_year BETWEEN 1700 AND 2200),
  website        url_text,
  logo_media_id  bigint REFERENCES media_assets (id) ON DELETE SET NULL,
  search_name    text GENERATED ALWAYS AS (normalize_ar(name)) STORED,   -- derived, DB-maintained
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX organizations_search_trgm ON organizations USING gin (search_name gin_trgm_ops);
CREATE INDEX organizations_sector_idx ON organizations (sector_id);
CREATE INDEX organizations_city_idx   ON organizations (city_id);

CREATE TABLE social_platforms (
  code     varchar(16) PRIMARY KEY CHECK (code ~ '^[a-z]+$'),
  name     varchar(40) NOT NULL,
  sort_order integer   NOT NULL DEFAULT 0
);

-- Optional SEO overrides; referenced 1:1 (UNIQUE FK) by posts, categories, pages, ...
CREATE TABLE seo_meta (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meta_title        varchar(70),
  meta_description  varchar(170),
  canonical_url     url_text,
  robots_noindex    boolean NOT NULL DEFAULT false,
  share_media_id    bigint REFERENCES media_assets (id) ON DELETE SET NULL,
  updated_at        timestamptz NOT NULL DEFAULT now()
);

-- External data providers (11, 12, 8, 19, 20) — switchable without code changes.
CREATE TABLE data_providers (
  code       varchar(32) PRIMARY KEY CHECK (code ~ '^[a-z0-9_]+$'),
  service    varchar(12) NOT NULL CHECK (service IN ('currency', 'weather', 'video', 'email', 'newsletter')),
  name       varchar(60) NOT NULL,
  is_active  boolean     NOT NULL DEFAULT false,
  is_backup  boolean     NOT NULL DEFAULT false
);
-- Exactly one active primary provider per service (partial unique index).
CREATE UNIQUE INDEX data_providers_one_primary_uq
  ON data_providers (service) WHERE is_active AND NOT is_backup;

CREATE TABLE provider_health (
  provider_code         varchar(32) PRIMARY KEY REFERENCES data_providers (code) ON DELETE CASCADE,
  last_success_at       timestamptz,
  last_failure_at       timestamptz,
  consecutive_failures  integer     NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
  last_error            varchar(1000),
  updated_at            timestamptz NOT NULL DEFAULT now()
);

-- Typed key/value site settings (21.13). Secrets never live here (.env only).
CREATE TABLE settings (
  key         varchar(80) PRIMARY KEY CHECK (key ~ '^[a-z_]+\.[a-z0-9_]+$'),   -- group.name
  value       text,
  value_type  varchar(8)  NOT NULL
              CHECK (value_type IN ('string', 'text', 'integer', 'boolean', 'url', 'email', 'phone', 'time', 'media')),
  updated_by  bigint REFERENCES users (id) ON DELETE SET NULL,
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CHECK (value IS NULL OR value_type <> 'integer' OR value ~ '^-?[0-9]+$'),
  CHECK (value IS NULL OR value_type <> 'boolean' OR value IN ('true', 'false')),
  CHECK (value IS NULL OR value_type <> 'url'     OR value ~* '^https?://'),
  CHECK (value IS NULL OR value_type <> 'time'    OR value ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  CHECK (value IS NULL OR value_type <> 'media'   OR value ~ '^[0-9]+$')
);

-- The platform's own social accounts (one row per platform, not one column each).
CREATE TABLE site_social_links (
  platform_code  varchar(16) PRIMARY KEY REFERENCES social_platforms (code) ON DELETE CASCADE,
  url            url_text    NOT NULL,
  sort_order     integer     NOT NULL DEFAULT 0,
  is_visible     boolean     NOT NULL DEFAULT true
);

-- Feature switches (21.14): booking, payments, accounts, chatbot, popup ad ...
CREATE TABLE feature_flags (
  key             varchar(32)  PRIMARY KEY CHECK (key ~ '^[a-z_]+$'),
  description_ar  varchar(200) NOT NULL,
  is_enabled      boolean      NOT NULL DEFAULT false,
  depends_on      varchar(32)  REFERENCES feature_flags (key) ON DELETE RESTRICT,
  updated_by      bigint REFERENCES users (id) ON DELETE SET NULL,
  updated_at      timestamptz  NOT NULL DEFAULT now(),
  CHECK (depends_on IS DISTINCT FROM key)
);

-- A child flag cannot be on while its parent is off (e.g. payments needs booking, 16.1).
CREATE FUNCTION trg_feature_flags_dependency() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.is_enabled AND NEW.depends_on IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM feature_flags WHERE key = NEW.depends_on AND is_enabled) THEN
    RAISE EXCEPTION 'Feature "%" requires "%" to be enabled first', NEW.key, NEW.depends_on
      USING ERRCODE = 'check_violation';
  END IF;
  IF NOT NEW.is_enabled
     AND EXISTS (SELECT 1 FROM feature_flags WHERE depends_on = NEW.key AND is_enabled) THEN
    RAISE EXCEPTION 'Disable the features that depend on "%" first', NEW.key
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER feature_flags_dependency
  BEFORE INSERT OR UPDATE ON feature_flags
  FOR EACH ROW EXECUTE FUNCTION trg_feature_flags_dependency();
