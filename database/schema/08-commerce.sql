  desktop_width        smallint CHECK (desktop_width  > 0),
  desktop_height       smallint CHECK (desktop_height > 0),
  mobile_width         smallint CHECK (mobile_width   > 0),
  mobile_height        smallint CHECK (mobile_height  > 0),   -- reserved sizes => no layout shift (13.10)
