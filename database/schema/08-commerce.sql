-- Booking reference numbers: RQ-<year>-<00001>, gap-free per year.
CREATE FUNCTION trg_bookings_reference() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.reference_year := local_year();
  NEW.reference_seq  := next_document_number('booking', NEW.reference_year);
  NEW.status_code    := 'new';
  RETURN NEW;
END $$;
CREATE TRIGGER bookings_reference
  BEFORE INSERT ON bookings
  FOR EACH ROW EXECUTE FUNCTION trg_bookings_reference();

-- First history row is written automatically.
CREATE FUNCTION trg_bookings_initial_history() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO booking_status_history (booking_id, status_code, note)
  VALUES (NEW.id, NEW.status_code, 'created');
  RETURN NULL;
END $$;
CREATE TRIGGER bookings_initial_history
  AFTER INSERT ON bookings
  FOR EACH ROW EXECUTE FUNCTION trg_bookings_initial_history();

-- Status changes happen ONLY by inserting a history row; the trigger validates
-- the move against booking_status_transitions and updates bookings.status_code.
CREATE FUNCTION trg_booking_history_apply() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_current varchar(16);
BEGIN
  SELECT status_code INTO v_current FROM bookings WHERE id = NEW.booking_id FOR UPDATE;
  IF NEW.status_code = v_current THEN
    RETURN NEW;                                   -- note only / initial row
  END IF;
  IF NOT EXISTS (SELECT 1 FROM booking_status_transitions
                 WHERE from_code = v_current AND to_code = NEW.status_code) THEN
    RAISE EXCEPTION 'Booking %: transition % -> % is not allowed', NEW.booking_id, v_current, NEW.status_code
      USING ERRCODE = 'check_violation';
  END IF;
  UPDATE bookings SET status_code = NEW.status_code WHERE id = NEW.booking_id;
  RETURN NEW;
END $$;
CREATE TRIGGER booking_history_apply
  BEFORE INSERT ON booking_status_history
  FOR EACH ROW EXECUTE FUNCTION trg_booking_history_apply();

-- Direct UPDATE of bookings.status_code is refused (keeps history complete).
CREATE FUNCTION trg_bookings_guard_status() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status_code IS DISTINCT FROM OLD.status_code AND pg_trigger_depth() < 2 THEN
    RAISE EXCEPTION 'Change booking status by inserting into booking_status_history'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER bookings_guard_status
  BEFORE UPDATE OF status_code ON bookings
  FOR EACH ROW EXECUTE FUNCTION trg_bookings_guard_status();

