CREATE VIEW live_ad_campaigns AS
SELECT c.*, p.placement_code
FROM ad_campaigns c
JOIN ad_campaign_placements p ON p.campaign_id = c.id
JOIN ad_placements pl ON pl.code = p.placement_code AND pl.is_enabled
WHERE c.status = 'active' AND c.starts_at <= now() AND c.ends_at > now();

