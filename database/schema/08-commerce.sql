-- Totals are computed, never stored (no update anomalies).
CREATE VIEW invoice_totals AS
SELECT i.id AS invoice_id,
       i.number,
       i.currency_code,
       s.subtotal,
       CASE WHEN i.tax_rate_bp IS NULL THEN 0
            ELSE round(s.subtotal * i.tax_rate_bp / 10000.0)::bigint END                    AS tax_amount,
       s.subtotal + CASE WHEN i.tax_rate_bp IS NULL THEN 0
            ELSE round(s.subtotal * i.tax_rate_bp / 10000.0)::bigint END                    AS total_amount
FROM invoices i
JOIN LATERAL (
  SELECT COALESCE(sum(round(l.quantity * l.unit_amount))::bigint, 0) AS subtotal
  FROM invoice_lines l WHERE l.invoice_id = i.id) s ON true;

