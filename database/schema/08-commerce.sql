  empty_behavior       varchar(5) NOT NULL DEFAULT 'house' CHECK (empty_behavior IN ('house', 'hide')),  -- 13.13
  frequency_cap_hours  smallint CHECK (frequency_cap_hours > 0),                                        -- 13.2
