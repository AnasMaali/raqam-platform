  created_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (payment_id, gateway_refund_id)
);

-- Refunds can never exceed what was paid.
CREATE FUNCTION trg_refunds_not_exceed() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_paid     bigint;
  v_refunded bigint;
BEGIN
  SELECT amount INTO v_paid FROM payments WHERE id = NEW.payment_id FOR UPDATE;
  SELECT COALESCE(sum(amount), 0) INTO v_refunded
  FROM refunds WHERE payment_id = NEW.payment_id AND status <> 'failed' AND id IS DISTINCT FROM NEW.id;
  IF NEW.status <> 'failed' AND v_refunded + NEW.amount > v_paid THEN
    RAISE EXCEPTION 'Refunds (%) would exceed the payment amount (%)', v_refunded + NEW.amount, v_paid
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER refunds_not_exceed
  BEFORE INSERT OR UPDATE ON refunds
  FOR EACH ROW EXECUTE FUNCTION trg_refunds_not_exceed();

