-- =====================================================================
--  02 · Media library (decision 9)
--  One row per uploaded file; generated sizes/formats in media_variants.
--  Alt text, caption, credit and focal point are typed columns (1NF),
--  not a JSON "custom_properties" bag.
-- =====================================================================

CREATE TABLE media_assets (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visibility        varchar(8)   NOT NULL DEFAULT 'public' CHECK (visibility IN ('public', 'private')),
  disk              varchar(8)   NOT NULL DEFAULT 'local'  CHECK (disk IN ('local', 'r2')),   -- 9.10
  path              varchar(500) NOT NULL,                  -- random file name (9.8)
  original_name     varchar(255) NOT NULL,
  mime_type         varchar(40)  NOT NULL CHECK (mime_type IN (
                      'image/jpeg', 'image/png', 'image/webp', 'image/avif', 'image/svg+xml',
                      'video/mp4', 'application/pdf', 'application/x-rive')),               -- 9.7
  size_bytes        bigint       NOT NULL CHECK (size_bytes > 0),
  checksum_sha256   sha256_hex   NOT NULL,
  width             integer      CHECK (width  > 0),
  height            integer      CHECK (height > 0),
  duration_seconds  numeric(7,2) CHECK (duration_seconds > 0),
  alt_text          varchar(250),
  caption           varchar(500),
  credit            varchar(200),
  focal_x           numeric(4,3) CHECK (focal_x BETWEEN 0 AND 1),                            -- 9.5
  focal_y           numeric(4,3) CHECK (focal_y BETWEEN 0 AND 1),
  uploaded_by       bigint REFERENCES users (id) ON DELETE SET NULL,
  created_at        timestamptz  NOT NULL DEFAULT now(),
  updated_at        timestamptz  NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  UNIQUE (disk, path),
  CHECK ((focal_x IS NULL) = (focal_y IS NULL)),
  -- 9.2: alt text is mandatory for every public raster/vector image
  CHECK (mime_type NOT LIKE 'image/%' OR visibility = 'private' OR alt_text IS NOT NULL),
  -- 9.9: size limits (stored file, after compression)
  CHECK (mime_type NOT LIKE 'image/%'      OR size_bytes <= 10 * 1024 * 1024),
  CHECK (mime_type <> 'application/pdf'    OR size_bytes <= 20 * 1024 * 1024),
  -- 8.11: short uploaded clips up to 90 s and 30 MB
  CHECK (mime_type <> 'video/mp4' OR (size_bytes <= 30 * 1024 * 1024
                                      AND duration_seconds IS NOT NULL AND duration_seconds <= 90))
);
CREATE INDEX media_assets_checksum_idx ON media_assets (checksum_sha256);
CREATE INDEX media_assets_recent_idx   ON media_assets (created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX media_assets_uploader_idx ON media_assets (uploaded_by);

-- Responsive renditions (9.3, 9.4): e.g. (42, 'md', 'avif')
CREATE TABLE media_variants (
  media_id    bigint       NOT NULL REFERENCES media_assets (id) ON DELETE CASCADE,
  variant     varchar(8)   NOT NULL CHECK (variant IN ('thumb', 'sm', 'md', 'lg', 'xl', 'og')),
  format      varchar(5)   NOT NULL CHECK (format IN ('avif', 'webp', 'jpeg', 'png')),
  width       integer      NOT NULL CHECK (width  > 0),
  height      integer      NOT NULL CHECK (height > 0),
  path        varchar(500) NOT NULL,
  size_bytes  bigint       NOT NULL CHECK (size_bytes > 0),
  PRIMARY KEY (media_id, variant, format)
);
