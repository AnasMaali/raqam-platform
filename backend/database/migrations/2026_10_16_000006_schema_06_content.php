-- A section post (and an infographic) must have its subtype row before it leaves draft.
-- DEFERRED constraint trigger: checked at COMMIT, so the post and its
-- subtype row can be inserted in either order inside one transaction.
CREATE FUNCTION trg_posts_subtype_present() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_table text := CASE NEW.kind_code
    WHEN 'episode'    THEN 'podcast_episodes'
    WHEN 'story'      THEN 'success_stories'
    WHEN 'product'    THEN 'products'
    WHEN 'history'    THEN 'history_entries'
    WHEN 'initiative' THEN 'initiatives'
    WHEN 'roundtable' THEN 'roundtable_sessions'
    WHEN 'awareness'  THEN 'awareness_cards'
    WHEN 'infographic' THEN 'infographics'          -- the downloadable file (9.11)
    ELSE NULL END;
  v_found boolean;
BEGIN
  IF v_table IS NULL OR NEW.status = 'draft' OR NEW.deleted_at IS NOT NULL THEN
    RETURN NULL;
  END IF;
  EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I WHERE post_id = $1)', v_table)
    INTO v_found USING NEW.id;
  IF NOT v_found THEN
    RAISE EXCEPTION 'Post % (kind %) needs its % row before leaving draft', NEW.id, NEW.kind_code, v_table
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER posts_subtype_present
  AFTER INSERT OR UPDATE ON posts
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION trg_posts_subtype_present();

